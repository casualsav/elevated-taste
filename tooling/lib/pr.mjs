/**
 * pr.mjs — Phase 3 PR opener. Opens ONE draft PR per new exemplar (so you can pick and choose
 * which sites to approve) via `gh`. It NEVER merges — merging each PR is your approval gate.
 *
 * Each PR stages only that exemplar's files: exemplars/<slug>.md + tokens/<slug>.json + the
 * patterns listed in its frontmatter. Screenshots stay gitignored; sources.json is derived and
 * left out of the PRs (dedupe reads the exemplar files directly). Dry mode prints the plan.
 */
import { spawnSync } from 'node:child_process';
import { readFileSync, existsSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(HERE, '..', '..');

function run(bin, args, dry) {
  if (dry) { console.log(`  ${bin} ${args.join(' ')}`); return { status: 0, stdout: bin === 'gh' ? 'https://github.com/<owner>/<repo>/pull/DRY' : '', stderr: '' }; }
  return spawnSync(bin, args, { cwd: ROOT, encoding: 'utf8' });
}

/** that exemplar's files: exemplar + tokens + the patterns named in its frontmatter. */
function exemplarFiles(corpus, slug) {
  const files = [`corpus/${corpus}/exemplars/${slug}.md`, `corpus/${corpus}/tokens/${slug}.json`];
  try {
    const md = readFileSync(join(ROOT, files[0]), 'utf8');
    const m = md.match(/^patterns:\s*\[([^\]]*)\]/m);
    if (m) for (const p of m[1].split(',').map((s) => s.trim().replace(/^["']|["']$/g, '')).filter(Boolean)) files.push(`corpus/${corpus}/patterns/${p}.md`);
  } catch { /* exemplar not on disk in dry mode */ }
  return files.filter((f) => existsSync(join(ROOT, f)) || false);
}

/**
 * Open one draft PR per distilled candidate. Returns the input array, each augmented with
 * `pr: { url, number, branch, draft }` on success or `error` on failure.
 */
export async function openPullRequests(distilled, { cfg = {}, dry = false, kind = 'evolve' } = {}) {
  dry = dry || process.env.EVOLVE_PR_DRY === '1';
  if (!distilled?.length) return [];
  if (!/^(evolve|refresh)$/.test(kind)) throw new Error(`unknown PR kind "${kind}"`);
  const verb = kind === 'refresh' ? 'Refresh' : 'Evolve';

  const date = new Date().toISOString().slice(0, 10);
  let base = (run('git', ['rev-parse', '--abbrev-ref', 'HEAD'], dry).stdout || '').trim();
  if (!base || base === 'HEAD') base = cfg.pr_base || 'main'; // detached HEAD (CI checkout) → configured base
  const draft = cfg.pr_draft !== false;
  const out = [];
  // Every failure below was returned on `.error` and printed by nobody, so a run that opened
  // zero PRs read exactly like one with nothing to open. Log at the point of failure, so every
  // caller sees it — not just evolve.mjs, which prints them after the fact.
  const fail = (c, msg) => { console.error(`  pr: ${c.slug} — ${msg}`); out.push({ ...c, error: msg }); };

  for (const c of distilled) {
    const branch = `${kind}/${date}-${c.slug}`;
    const files = dry ? [`corpus/${c.corpus}/exemplars/${c.slug}.md`, `corpus/${c.corpus}/tokens/${c.slug}.json`, '<patterns from frontmatter>'] : exemplarFiles(c.corpus, c.slug);
    if (!dry && files.length < 2) { fail(c, 'distilled files missing on disk'); continue; }

    const title = `${verb}: ${c.slug} (${c.corpus})`;
    const repoSlug = process.env.GITHUB_REPOSITORY || null; // set in Actions; captures land on the `captures` branch right after the PRs open
    const body = [
      `New exemplar distilled from ${c.url}`, '',
      `**Source site:** ${c.url}`,
      ...(repoSlug ? [`**Captures:** https://github.com/${repoSlug}/tree/captures/corpus/${c.corpus}/screenshots/${c.slug}`] : []),
      '',
      'Draft - open the source above, review the distilled principles / tokens / patterns in this',
      'diff, then **merge to add this site** to the corpus, or **close to skip it**. One PR per site',
      'so you can pick and choose. Merging is the only thing that folds it in.', '',
      'Generated by tooling/evolve.mjs',
    ].join('\n');

    // A failed branch create MUST abort this site: proceeding would `git add` + commit onto
    // whatever branch is checked out (main, on a same-day re-run when evolve/<date>-<slug>
    // already exists).
    let r = run('git', ['checkout', '-b', branch, base], dry);
    if (!dry && r.status !== 0) { fail(c, `branch create failed (exists already?): ${(r.stderr || '').trim().slice(0, 120)}`); continue; }
    r = run('git', ['add', ...files], dry);
    if (!dry && r.status !== 0) { run('git', ['checkout', base], false); fail(c, 'git add failed'); continue; }
    r = run('git', ['commit', '-m', title], dry);
    if (!dry && r.status !== 0) { run('git', ['checkout', base], false); fail(c, 'commit failed'); continue; }
    r = run('git', ['push', '-u', 'origin', branch], dry);
    if (!dry && r.status !== 0) { run('git', ['checkout', base], false); fail(c, 'push failed'); continue; }
    const ghArgs = ['pr', 'create', '--base', base, '--head', branch, '--title', title, '--body', body];
    if (draft) ghArgs.push('--draft');
    r = run('gh', ghArgs, dry);
    run('git', ['checkout', base], dry);
    if (!dry && r.status !== 0) { fail(c, `gh pr create: ${(r.stderr || '').slice(0, 120)}`); continue; }
    const url = (r.stdout || '').trim().split('\n').filter(Boolean).pop() || null;
    out.push({ ...c, pr: { url, branch, draft } });
  }
  return out;
}

if (resolve(process.argv[1] || '') === resolve(fileURLToPath(import.meta.url))) {
  openPullRequests([{ slug: 'attio', corpus: 'production', url: 'https://attio.com' }, { slug: 'auralite', corpus: 'expressive', url: 'https://auralite.io' }], { dry: true })
    .then((rs) => console.log('would open ' + rs.length + ' per-site draft PR(s)'));
}
